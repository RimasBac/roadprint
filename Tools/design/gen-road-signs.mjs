// Turns Design/road-signs (the Designer's SVG templates and signs.json) into what the app draws:
// - App/Assets.xcassets/RoadSigns/RoadSign-<template>.imageset: each SVG, kept as a vector;
// - App/Design/RoadSigns.generated.swift: the templates, text boxes and selection rules.
// No npm dependencies. Run from any directory: node Tools/design/gen-road-signs.mjs
// CI runs it and fails when the committed output differs.
import { readFileSync, writeFileSync, mkdirSync, rmSync, copyFileSync, existsSync } from 'node:fs';


const root = new URL('../../', import.meta.url);
const signsDir = new URL('Design/road-signs/', root);
const catalogDir = new URL('App/Assets.xcassets/RoadSigns/', root);
const swiftURL = new URL('App/Design/RoadSigns.generated.swift', root);

const spec = JSON.parse(readFileSync(new URL('signs.json', signsDir), 'utf8'));
const fail = message => { throw new Error(message); };

const json = value => JSON.stringify(value, null, 2) + '\n';
const asset = name => `RoadSign-${name}`;
const num = value => {
  if (typeof value !== 'number' || !Number.isFinite(value)) fail(`not a number: ${value}`);
  return Number.isInteger(value) ? `${value}` : `${value}`;
};
const rawString = text => {
  if (text.includes('"#')) fail(`regex can't go in a raw string: ${text}`);
  return `#"${text}"#`;
};
const optString = value => (value === undefined ? 'nil' : `"${value}"`);
const optInt = value => (value === undefined ? 'nil' : num(value));
function color(hex) {
  const m = /^#([0-9a-f]{6})$/i.exec(hex) ?? fail(`bad colour ${hex}`);
  const [r, g, b] = [0, 2, 4].map(i => parseInt(m[1].slice(i, i + 2), 16) / 255);
  return `Color(red: ${r}, green: ${g}, blue: ${b})`;
}

// ---- asset catalog
const templates = Object.entries(spec.templates).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
rmSync(catalogDir, { recursive: true, force: true });
mkdirSync(catalogDir, { recursive: true });
writeFileSync(new URL('Contents.json', catalogDir), json({ info: { author: 'xcode', version: 1 } }));
for (const [name, template] of templates) {
  const source = new URL(template.file, signsDir);
  if (!existsSync(source)) fail(`missing ${template.file}`);
  const svg = readFileSync(source, 'utf8');
  if (/<text|<image|<style|filter=|mask=|clip-path=|gradient/i.test(svg)) fail(`${template.file}: only flat paths and rects convert to a vector asset`);
  const set = new URL(`${asset(name)}.imageset/`, catalogDir);
  mkdirSync(set, { recursive: true });
  copyFileSync(source, new URL(template.file, set));
  writeFileSync(new URL('Contents.json', set), json({
    images: [{ filename: template.file, idiom: 'universal' }],
    info: { author: 'xcode', version: 1 },
    properties: { 'preserves-vector-representation': true },
  }));
}

// ---- Swift
const height = spec.viewBoxHeight;
const templateLines = templates.map(([name, t]) => {
  const [x0, y0, w, h] = t.viewBox;
  if (x0 !== 0 || y0 !== 0 || h !== height) fail(`${name}: viewBox must be 0 0 w ${height}`);
  if (t.display?.show !== 'ref') fail(`${name}: only display.show = "ref" is supported`);
  return `        "${name}": Template(
            asset: "${asset(name)}", width: ${num(w)},
            textBox: CGRect(x: ${num(t.textBox.x)}, y: ${num(t.textBox.y)}, width: ${num(t.textBox.width)}, height: ${num(t.textBox.height)}),
            textColor: ${color(t.textColor)},
            fontSize: ${num(t.fontSize)}, baseline: ${num(t.baseline)}, tracking: ${num(t.tracking ?? 0)},
            minScale: ${num(t.minScale ?? spec.minScale)}, uppercase: ${t.display.uppercase ? 'true' : 'false'}),`;
});
const rule = (r, indent) => `${indent}Rule(template: "${r.template}", wide: ${optString(r.wide)}, wideAbove: ${optInt(r.wideAbove)},
${indent}     small: ${optString(r.small)}, wideSmall: ${optString(r.wideSmall)}, smallBelow: ${optInt(r.smallBelow)})`;
const networks = Object.entries(spec.networks).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
for (const [, n] of networks) {
  for (const name of [n.template, n.wide, n.small, n.wideSmall, ...(n.variants ?? []).flatMap(v => [v.template, v.wide, v.small, v.wideSmall])]) {
    if (name !== undefined && !spec.templates[name]) fail(`unknown template ${name}`);
  }
}
const networkLines = networks.map(([name, n]) => {
  const variants = (n.variants ?? []).map(v => `                Variant(match: ${rawString(v.match)},
${rule(v, '                        ')}),`);
  return `        .${name}: Network(
            accept: ${rawString(n.accept)},
${rule(n, '            ')},
            variants: [${variants.length ? '\n' + variants.join('\n') + '\n            ' : ''}]),`;
});

const swift = `// Generated by Tools/design/gen-road-signs.mjs from Design/road-signs/signs.json. Do not edit.
import SwiftUI
import RoadPrintCore

/// The road-sign templates (Design/road-signs/README.md) as the app uses them. All lengths are in
/// viewBox units; every sign is \`viewBoxHeight\` units tall.
enum RoadSignSpec {
    struct Template: Sendable {
        /// Asset catalog image: the empty sign as a vector.
        let asset: String
        let width: CGFloat
        let textBox: CGRect
        let textColor: Color
        let fontSize: CGFloat
        let baseline: CGFloat
        let tracking: CGFloat
        let minScale: CGFloat
        let uppercase: Bool
    }

    struct Rule: Sendable {
        let template: String
        let wide: String?
        let wideAbove: Int?
        let small: String?
        let wideSmall: String?
        let smallBelow: Int?
    }

    struct Variant: Sendable {
        let match: String
        let rule: Rule

        init(match: String, _ rule: Rule) {
            self.match = match
            self.rule = rule
        }
    }

    struct Network: Sendable {
        let accept: String
        let rule: Rule
        let variants: [Variant]

        init(accept: String, _ rule: Rule, variants: [Variant]) {
            self.accept = accept
            self.rule = rule
            self.variants = variants
        }
    }

    static let viewBoxHeight: CGFloat = ${num(height)}
    /// Cap height of the number font as a share of its size.
    static let capHeight: CGFloat = 0.7

    static let templates: [String: Template] = [
${templateLines.join('\n')}
    ]

    static let networks: [RoadNetwork: Network] = [
${networkLines.join('\n')}
    ]
}
`;
writeFileSync(swiftURL, swift);
console.log(`road signs: ${templates.length} templates, ${networks.length} networks`);
